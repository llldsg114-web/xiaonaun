  /** 候选 F·F2：进程内 LRU 去重（不写 S、刷新即忘、零外发）。
   * 键 tone+':'+intent（DEFAULT_POOL 用固定键 'default'）；排除近 WINDOW 条，全排除则回退全池。 */
  var WINDOW = 8;
  var recentUsed = {};
  function pickDedup(poolKey, pool) {
    var recent = recentUsed[poolKey] || [];
    var avail = pool.filter(function (s) { return recent.indexOf(s) < 0; });
    var chosen = pick(avail.length ? avail : pool);
    recent.push(chosen);
    if (recent.length > WINDOW) recent = recent.slice(recent.length - WINDOW);
    recentUsed[poolKey] = recent;
    return chosen;
  }

  /** 候选 F·F8：取情境变体（时间窗 + affection 分桶），无匹配则返回空数组 */
  function contextVariant(intent, ctx) {
    var cv = CONTEXT_VARIANT[intent];
    if (!cv) return [];
    var out = [];
    var h = new Date(Date.now()).getHours();
    var tb = (h >= 6 && h <= 10) ? 'early' : (h >= 11 && h <= 17) ? 'noon'
            : (h >= 18 && h <= 23) ? 'evening' : 'late';
    if (cv.time && cv.time[tb]) out = out.concat(cv.time[tb]);
    var aff = (ctx && typeof ctx.affection === 'number') ? ctx.affection : NaN;
    var ab = isNaN(aff) ? null : (aff < 2 ? 'low' : (aff <= 4 ? 'mid' : 'high'));
    if (ab && cv.aff && cv.aff[ab]) out = out.concat(cv.aff[ab]);
    return out;
  }

  /**
   * 轻量意图识别：返回命中的意图键，未命中返回 null。
   * 优先级：love > miss > sad > busy > thanks > sorry > praise > concern > bye > greeting > question。
   * @param {string} text
   * @returns {string|null}
   */
  function detectIntent(text) {
    if (hasAny(text, ['爱你', '喜欢你', '爱死', '喜欢死', '么么', '亲亲', '抱抱', '好爱', '超爱']))
      return 'love';
    if (hasAny(text, ['想你', '想我', '想念', '挂念', '好想你', '想死你']))
      return 'miss';
    if (hasAny(text, ['难过', '伤心', '不开心', '郁闷', '焦虑', '累', '疲惫', '崩溃', '委屈', '哭', '压力', '烦', '难受', '孤独', '孤单', '失落', '委屈', '丧', 'emo']))
      return 'sad';
    if (hasAny(text, ['忙', '加班', '开会', '没空', '没时间', '赶工', '出差', '工作']))
      return 'busy';
    if (hasAny(text, ['谢谢', '感谢', '多谢', '谢啦', '谢了', '辛苦了']))
      return 'thanks';
    if (hasAny(text, ['对不起', '抱歉', '道歉', '不好意思', '我的错']))
      return 'sorry';
    if (hasAny(text, ['漂亮', '可爱', '好看', '聪明', '乖', '棒', '厉害', '好看', '美']))
      return 'praise';
    if (hasAny(text, ['吃饭', '吃了吗', '饿', '喝水', '早点睡', '注意身体', '照顾好', '休息好', '别熬夜']))
      return 'concern';
    if (hasAny(text, ['晚安', '睡了', '睡觉', '拜拜', '再见', '走了', '下了', '休息', '安啦', '安安']))
      return 'bye';
    if (hasAny(text, ['你好', '您好', '在吗', '在不在', '在么', '早', '早上好', '晚上好', '嗨', '哈喽', 'hi', 'hello', '在不在呀']))
      return 'greeting';
    // 疑问句（以问号 / 吗 / 呢 结尾或含疑问词）
    if (/[?？]$/.test(text.trim()) || /(吗|呢|怎么|为什么|如何|啥|什么|哪|几|谁)\b/.test(text) || /(怎么|为什么|如何)了?$/.test(text.trim()))
      return 'question';
    return null;
  }

