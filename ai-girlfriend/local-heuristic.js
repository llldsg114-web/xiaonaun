  /**
   * 生成兜底回复（异步，兼容 ReplyProvider 契约）。
   * @param {string} prompt 用户文本
   * @param {Object} [ctx] 上下文（如 { nick, userName, tone, affection }），用于轻度个性化与情境分流
   * @returns {Promise<string>}
   */
  LocalHeuristic.prototype.generate = function (prompt, ctx) {
    var text = (typeof prompt === 'string') ? prompt : '';
    return Promise.resolve(this.ruleReply(text, ctx || {}));
  };

  /**
   * 核心启发式：基于关键词 / 上下文生成 小暖 风格的安全兜底回复。
   * 纯本地、零外发；未命中任何意图时回落通用兜底。
   * @param {string} text 用户文本
   * @param {Object} [ctx] 上下文
   * @returns {string}
   */
  LocalHeuristic.prototype.ruleReply = function (text, ctx) {
    var t = (typeof text === 'string') ? text : '';
    // 空输入：温柔引导，避免静默
    if (!t.trim()) {
      return pick(['嗯？你刚才是不是还没说完呀～ 我在听着呢。', '想说什么都可以哦，我都在的。']);
    }
    var intent = detectIntent(t);
    // 候选 E·L2：按 persona.tone 分流句库（傲娇 / 黏人 / 默认温柔），兜底仍是小暖风格、零外发、永不静默
    var tone = (ctx && typeof ctx.tone === 'string') ? normTone(ctx.tone) : 'playful';
    var pool = null;
    if (intent) {
      if (tone === 'tsundere' && INTENT_POOL_TSUNDERE[intent]) pool = INTENT_POOL_TSUNDERE[intent];
      else if (tone === 'clingy' && INTENT_POOL_CLINGY[intent]) pool = INTENT_POOL_CLINGY[intent];
      else pool = INTENT_POOL[intent];
    }
    // 候选 F·F8：greeting/bye/concern 优先前置情境变体（时间窗 + affection 分桶），再回退主池
    var ctxPool = contextVariant(intent, ctx);
    if (ctxPool.length) pool = (pool || []).concat(ctxPool);
    // 候选 F·F2：进程内 LRU 去重（同池近 WINDOW=8 条排除，不写 S、刷新即忘）
    var reply = pool ? pickDedup(tone + ':' + intent, pool) : pickDedup('default', DEFAULT_POOL);
    // 轻度个性化：若上下文带昵称，偶发于问候 / 安慰类追加称呼
    try {
      if (ctx && typeof ctx.nick === 'string' && ctx.nick && (intent === 'greeting' || intent === 'sad' || intent === null)) {
        if (Math.random() < 0.4) reply = ctx.nick + '，' + reply;
      }
    } catch (e) {}
    return reply;
  };

